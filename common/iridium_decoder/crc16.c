uint16_t crc16_ccitt_false(const uint8_t *data, size_t n_bytes)
{
    uint16_t crc = 0xFFFFu;
    for (size_t i = 0; i < n_bytes; i++) {
        crc = (uint16_t)((crc << 8) ^
                         crc16_ccitt_table[((crc >> 8) ^ data[i]) & 0xFFu]);
    }
    return crc;
}

